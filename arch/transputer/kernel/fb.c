/*
 * Transputer Framebuffer Console
 *
 * Self-contained framebuffer console for the T4 emulator's built-in
 * VGA controller. Writes 32-bit ARGB pixels to the firmware-owned RAM
 * surface at TRANSPUTER_FB_BASE (top 2 MiB of the 32 MiB window —
 * 0x81E00000) and renders text using an embedded 8x16 VGA font.
 *
 * T4 presents that surface via SDL (and still accepts the legacy
 * 0x90000000 alias). CHDL maps the same range as ordinary RAM after
 * memblock_reserve(). Pass "transputer_nofb" to skip console init when
 * the host has no display path (keeps cycle-accurate CHDL boots moving).
 *
 * Both UART and FB consoles coexist: UART provides host-side logging,
 * FB provides on-screen display.
 *
 * Future optimization: the transputer's MOVE2D instruction (move2dinit +
 * move2dall, opcodes 0x5b/0x5c) could accelerate fb_scroll() by doing
 * hardware-assisted 2D block moves instead of word-at-a-time copies.
 */

